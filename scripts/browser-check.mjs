/** Real UI against synthetic HTTP servers only. No live CRM token or writes. */
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { chromium } from 'playwright';
import { sandbox, scenario, TOKEN } from '../fixtures/http.js';
import { CrmClient } from '../src/crm.js';
import { Store } from '../src/store.js';
import { ReviewService } from '../src/service.js';
import { scrapeSnapshot } from '../src/scraper.js';
import { startReviewServer } from '../src/review-server.js';
const data = scenario(); data.accounts.find(a => a.id === 'north').name = 'Facility North Old Name';
const api = await sandbox(data), dir = await mkdtemp(join(tmpdir(), 'browser-'));
const store = new Store(dir, 'browser');
const service = new ReviewService({ config: api.config, client: new CrmClient(api.config, TOKEN), store, readWebsite: () => scrapeSnapshot(api.config) });
const app = await startReviewServer(service, { port: 0, fields: api.config.fields });
const browser = await chromium.launch(), page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [], checks = []; page.on('pageerror', error => errors.push(error.message));
await mkdir('artifacts', { recursive: true });
try {
  await page.goto(app.url); await page.getByText('NOT SCANNED', { exact: false }).waitFor();
  assert.equal(await page.locator('#version').innerText(), 'v2.3.0'); checks.push('Initial status and version.');
  api.flags.invalidId = true; await page.locator('#scan').click(); await page.getByText('SCAN FAILED', { exact: false }).waitFor();
  assert.match(await page.locator('#scan-status').innerText(), /Zero proposals is not a finding/);
  await page.screenshot({ path: 'artifacts/scan-failed.png', fullPage: true });
  await page.reload(); await page.getByText('SCAN FAILED', { exact: false }).waitFor(); checks.push('Failure persists across reload, not zero inconsistencies.');
  api.flags.invalidId = false; await page.locator('#scan').click(); await page.getByText('SCAN SUCCEEDED', { exact: false }).waitFor();
  assert.match(await page.locator('#company').innerText(), /Example Senior Living/); assert.match(await page.locator('#company').innerText(), /ZIP not published/);
  await page.locator('#reviewer').fill('Browser QA');
  await page.locator('#queue button').filter({ hasText: 'Repeated facility-field corrections' }).click();
  assert.match(await page.locator('#detail').innerText(), /2 proposed records/);
  assert.equal(await page.locator('#detail button').filter({ hasText: /^Approve and write to CRM$/ }).count(), 2);
  await page.screenshot({ path: 'artifacts/grouped-review.png', fullPage: true }); checks.push('Company, groups and individual decisions render.');
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Approve all 2 reviewed changes', exact: true }).click();
  await page.getByText('Applied 2, blocked 0', { exact: false }).waitFor(); assert.equal(api.writes.length, 2); checks.push('Batch approval verifies two records.');
  await page.locator('#scan').click(); await page.getByText('Scan complete:', { exact: false }).waitFor();
  await page.locator('#queue button').filter({ hasText: 'Administrator contact corrections' }).click();
  assert.match(await page.locator('#detail').innerText(), /Ada Example/);
  page.once('dialog', dialog => dialog.accept()); await page.getByRole('button', { name: 'Reject — no CRM write', exact: true }).click();
  await page.getByText('Rejection saved.', { exact: false }).waitFor();
  await page.locator('#scan').click(); await page.getByText('Scan complete:', { exact: false }).waitFor();
  assert.equal(await page.locator('#queue button').filter({ hasText: 'Administrator contact corrections' }).count(), 0);
  assert.equal(await page.locator('#queue button').filter({ hasText: 'Repeated facility-field corrections' }).count(), 0);
  assert.equal(api.writes.length, 2); checks.push('Rejection and rerun preserve decisions without extra writes.');
  await page.locator('#queue button').filter({ hasText: 'CHOW / protected billing history' }).click();
  const text = await page.locator('#detail').innerText(); assert.match(text, /Other Operator \(Parent Account\)/); assert.match(text, /CHOW safeguard/); assert.match(text, /300/); assert.match(text, /40/);
  checks.push('Parent names, financial values and CHOW safeguard display.');
  await page.locator('summary').filter({ hasText: 'Matched facilities and read-only contact context' }).click();
  await page.locator('#matches summary').filter({ hasText: 'Facility North' }).click();
  assert.match(await page.locator('#matches').innerText(), /Same care category:/); checks.push('Care synonym is visible.');
  api.flags.invalidId = true; await page.locator('#scan').click(); await page.getByText('SCAN FAILED', { exact: false }).waitFor();
  assert.match(await page.locator('#scan-status').innerText(), /stale/);
  assert.equal(await page.getByRole('button', { name: 'Approve and write to CRM', exact: true }).isDisabled(), true); checks.push('Stale approval disabled after failed rescan.');
  assert.deepEqual(errors, []); checks.push('No browser JavaScript errors.');
  await writeFile('artifacts/browser.json', JSON.stringify({ passed: checks.length, checks, errors }, null, 2));
  console.log(JSON.stringify({ browserChecks: checks.length, checks, errors }));
} catch (error) { await page.screenshot({ path: 'artifacts/browser-failure.png', fullPage: true }); throw error; }
finally { await browser.close(); await app.close(); store.close(); await api.close(); await rm(dir, { recursive: true, force: true }); }
